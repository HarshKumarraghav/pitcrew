import { createHash } from "node:crypto";
import { mkdirSync, writeFileSync, readFileSync, existsSync } from "node:fs";
import { homedir } from "node:os";
import { join, resolve, basename } from "node:path";
import { readSources, gitFacts, type GitFacts, type SourceFile } from "./scan.ts";
import { buildModules, type ModuleInfo } from "./symbols.ts";
import { profileProject, type ProjectProfile } from "./profile.ts";
import { BM25 } from "./bm25.ts";

export interface ProjectIndex {
  root: string;
  id: string;
  createdAt: string;
  git: GitFacts;
  profile: ProjectProfile;
  modules: ModuleInfo[];
}

export function projectId(root: string): string {
  const abs = resolve(root);
  return `${basename(abs).replace(/[^\w.-]+/g, "-")}-${createHash("sha1").update(abs).digest("hex").slice(0, 8)}`;
}

export function projectDir(root: string, stateDir = join(homedir(), ".pitcrew")): string {
  return join(stateDir, "projects", projectId(root));
}

/** Deterministic scan: every fact here comes from files, manifests or git — no model involved. */
export function scanProject(root: string): { index: ProjectIndex; sources: SourceFile[] } {
  const abs = resolve(root);
  const sources = readSources(abs);
  const modules = buildModules(sources);
  const profile = profileProject(abs, sources, modules);
  return {
    index: { root: abs, id: projectId(abs), createdAt: new Date().toISOString(), git: gitFacts(abs), profile, modules },
    sources,
  };
}

function bullets(xs: string[], empty = "_none detected_"): string {
  return xs.length ? xs.map((x) => `- ${x}`).join("\n") : empty;
}

export function renderArtifacts(ix: ProjectIndex): Record<string, string> {
  const p = ix.profile;
  const code = ix.modules.filter((m) => !m.isTest);
  const fanIn = new Map<string, number>();
  for (const m of ix.modules) for (const d of m.internalDeps) fanIn.set(d, (fanIn.get(d) ?? 0) + 1);
  const core = [...fanIn].sort((a, b) => b[1] - a[1]).slice(0, 10);
  const header = `<!-- generated by pitcrew scout from ${ix.root} @ ${ix.git.head ?? "working tree"} on ${ix.createdAt}. Facts are deterministic (files, manifests, git). -->\n`;

  const overview = `${header}# ${p.name} — product overview

${p.description ?? "_No description in package metadata._"}

| | |
|---|---|
| Languages | ${p.languages.map((l) => `${l.lang} (${l.files} files, ${l.lines} lines)`).join(", ")} |
| Frameworks | ${p.frameworks.join(", ") || "none detected"} |
| Package manager | ${p.packageManager ?? "unknown"} |
| Databases | ${p.databases.join(", ") || "none detected"} |
| Auth | ${p.auth.join(", ") || "none detected"} |
| Integrations | ${p.integrations.join(", ") || "none detected"} |
| Test runner | ${p.testRunner ?? "unknown"} — \`${p.testCommand ?? "?"}\` |
| Git | ${ix.git.isRepo ? `${ix.git.commits} commits, HEAD ${ix.git.head}` : "not a git repository"} |

## Entry points
${bullets(p.entryPoints.map((e) => `\`${e}\``))}

## HTTP routes
${bullets(p.routes.map((r) => `\`${r.route}\` — \`${r.file}\``))}

## README (excerpt)
${p.readme ? p.readme.split("\n").slice(0, 30).join("\n") : "_no README_"}
`;

  const arch = `${header}# ${p.name} — architecture

## Layers (by directory)
| directory | files | inferred role |
|---|---|---|
${p.dirs.map((d) => `| \`${d.dir}\` | ${d.files} | ${d.role || "—"} |`).join("\n")}

## Most depended-on modules (fan-in)
${bullets(core.map(([f, n]) => `\`${f}\` — imported by ${n} module(s)`))}

## Module dependencies
${code.filter((m) => m.internalDeps.length).map((m) => `- \`${m.path}\` → ${m.internalDeps.map((d) => `\`${d}\``).join(", ")}`).join("\n") || "_no internal imports found_"}

## External packages
${bullets([...new Set(ix.modules.flatMap((m) => m.externalDeps))].sort().map((d) => `\`${d}\``))}
`;

  const conventions = `${header}# ${p.name} — engineering conventions

${bullets(p.conventions)}

## Scripts
${bullets(Object.entries(p.scripts).map(([k, v]) => `\`${k}\`: \`${v}\``))}

## Frequently changed files (last 500 commits)
${bullets((ix.git.hotFiles ?? []).map((h) => `\`${h.path}\` (${h.changes})`))}

## Recent commits
${bullets((ix.git.recent ?? []).map((c) => `\`${c}\``))}
`;

  const tests = ix.modules.filter((m) => m.isTest);
  const testing = `${header}# ${p.name} — testing guide

- Runner: **${p.testRunner ?? "unknown"}**
- Run all tests: \`${p.testCommand ?? "unknown"}\`
${p.buildCommand ? `- Build: \`${p.buildCommand}\`\n` : ""}- Test files: ${tests.length}

| test file | imports (code under test) |
|---|---|
${tests.map((t) => `| \`${t.path}\` | ${t.internalDeps.map((d) => `\`${d}\``).join(", ") || "—"} |`).join("\n")}
`;

  const moduleMap = ix.modules.map((m) => ({
    path: m.path,
    lang: m.lang,
    lines: m.lines,
    isTest: m.isTest,
    exports: m.symbols.filter((s) => s.exported).map((s) => `${s.kind} ${s.name}:${s.line}`),
    symbols: m.symbols.length,
    routes: m.routes,
  }));
  const graph = {
    nodes: ix.modules.map((m) => m.path),
    edges: ix.modules.flatMap((m) => m.internalDeps.map((d) => ({ from: m.path, to: d }))),
    external: Object.fromEntries(ix.modules.filter((m) => m.externalDeps.length).map((m) => [m.path, m.externalDeps])),
  };

  return {
    "PRODUCT_OVERVIEW.md": overview,
    "ARCHITECTURE.md": arch,
    "ENGINEERING_CONVENTIONS.md": conventions,
    "TESTING_GUIDE.md": testing,
    "MODULE_MAP.json": JSON.stringify(moduleMap, null, 2),
    "DEPENDENCY_GRAPH.json": JSON.stringify(graph, null, 2),
  };
}

/** Scan, render and persist artifacts outside the repository. Returns the artifact directory. */
export function scout(root: string, stateDir?: string): { dir: string; index: ProjectIndex; files: string[] } {
  const { index } = scanProject(root);
  const dir = projectDir(root, stateDir);
  mkdirSync(dir, { recursive: true });
  const artifacts = renderArtifacts(index);
  for (const [name, content] of Object.entries(artifacts)) writeFileSync(join(dir, name), content);
  writeFileSync(join(dir, "index.json"), JSON.stringify(index));
  return { dir, index, files: Object.keys(artifacts) };
}

export function loadIndex(root: string, stateDir?: string): ProjectIndex | undefined {
  const p = join(projectDir(root, stateDir), "index.json");
  return existsSync(p) ? (JSON.parse(readFileSync(p, "utf8")) as ProjectIndex) : undefined;
}

export interface ContextHit {
  path: string;
  score: number;
  why: string[];
  symbols: string[];
}

/**
 * Retrieve the files most relevant to a task: BM25 over paths, symbol names and source text,
 * exact-symbol boosts, then one hop along the import graph (both directions) with decay, and
 * the tests that import the chosen files.
 */
export function retrieve(root: string, task: string, opts: { k?: number; sources?: SourceFile[]; index?: ProjectIndex } = {}): ContextHit[] {
  const k = opts.k ?? 8;
  const { index, sources } = opts.index && opts.sources ? { index: opts.index, sources: opts.sources } : scanProject(root);
  const text = new Map(sources.map((s) => [s.path, s.text]));
  const mods = new Map(index.modules.map((m) => [m.path, m]));
  const bm = new BM25(
    index.modules.map((m) => ({
      id: m.path,
      fields: [
        { text: m.path.replace(/[/.]/g, " "), weight: 3 },
        { text: m.symbols.map((s) => s.name).join(" "), weight: 2 },
        { text: m.routes.join(" "), weight: 2 },
        { text: text.get(m.path) ?? "", weight: 1 },
      ],
    })),
  );
  const scores = new Map<string, { score: number; why: Set<string> }>();
  const bump = (p: string, s: number, why: string) => {
    const e = scores.get(p) ?? { score: 0, why: new Set<string>() };
    e.score += s;
    e.why.add(why);
    scores.set(p, e);
  };
  const hits = bm.search(task, 30);
  const top = hits[0]?.score ?? 1;
  for (const h of hits) bump(h.id, h.score / top, `matches: ${h.matched.slice(0, 5).join(", ")}`);

  // Exact identifiers mentioned in the task (e.g. `getAllTasks`, TaskStore).
  const idents = new Set(task.match(/[A-Za-z_$][\w$]{2,}/g) ?? []);
  for (const m of index.modules) {
    for (const s of m.symbols) if (idents.has(s.name)) bump(m.path, 1.0, `defines \`${s.name}\``);
    for (const id of idents) if (id.length > 3 && (text.get(m.path) ?? "").includes(id) && /[A-Z_]/.test(id.slice(1))) bump(m.path, 0.3, `uses \`${id}\``);
  }

  // Dependency expansion from the strongest seeds.
  const seeds = [...scores].sort((a, b) => b[1].score - a[1].score).slice(0, 5);
  for (const [p, { score }] of seeds) {
    const m = mods.get(p);
    for (const d of m?.internalDeps ?? []) bump(d, score * 0.35, `imported by \`${p}\``);
    for (const other of index.modules) if (other.internalDeps.includes(p) && !other.isTest) bump(other.path, score * 0.25, `imports \`${p}\``);
  }
  const ranked = [...scores].filter(([p]) => !mods.get(p)?.isTest).sort((a, b) => b[1].score - a[1].score).slice(0, k);
  const chosen = new Set(ranked.map(([p]) => p));
  // Related tests, ranked after code.
  const testHits = index.modules
    .filter((m) => m.isTest && m.internalDeps.some((d) => chosen.has(d)))
    .map((m) => [m.path, { score: 0.01, why: new Set([`tests ${m.internalDeps.filter((d) => chosen.has(d)).map((d) => `\`${d}\``).join(", ")}`]) }] as const);
  return [...ranked, ...testHits].map(([path, { score, why }]) => ({
    path,
    score: Math.round(score * 1000) / 1000,
    why: [...why].slice(0, 3),
    symbols: (mods.get(path)?.symbols ?? []).filter((s) => s.exported).slice(0, 8).map((s) => `${s.name}:${s.line}`),
  }));
}

/** Markdown context block suitable for pasting into an agent prompt. */
export function formatContext(task: string, hits: ContextHit[], ix?: ProjectIndex): string {
  const p = ix?.profile;
  const head = p
    ? `Project: ${p.name} · ${p.languages.map((l) => l.lang).join("/")} · frameworks: ${p.frameworks.join(", ") || "none"} · tests: \`${p.testCommand ?? "?"}\`\n`
    : "";
  return `${head}Relevant files for: "${task}"\n${hits.map((h, i) => `${i + 1}. ${h.path}  — ${h.why.join("; ")}${h.symbols.length ? `\n   symbols: ${h.symbols.join(", ")}` : ""}`).join("\n")}\n`;
}
